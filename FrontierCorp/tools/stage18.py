def _tech(tech):
    mid = tech.get("t_transport") or tech.get("t_special")
    late = tech.get("t_mk4") or tech.get("t_teleport")
    if mid:
        mid.setdefault("unlocks", {}).setdefault("buildings", []).append("builder_bay")
    if late:
        late.setdefault("unlocks", {}).setdefault("buildings", []).append("builder_bay_mk2")


def _waves(waves, menu, quests):
    waves.update({"first_delay": 1200, "interval": 900, "interval_step": 20, "interval_min": 600})
    menu["victory"] = {"mode": "none", "value": 0}
    if "q_win" in quests:
        quests["q_win"].update({"text": "Рекорд: отбейте 20 волн роботов (волны бесконечные — держитесь дальше!)", "reward": 2000})
    quests["q_waves50"] = {"text": "Рекорд: отбейте 50 волн роботов", "order": 16, "reward": 6000, "goal": "waves", "n": 50,
                           "item": "", "buildings": [], "hint": ""}


