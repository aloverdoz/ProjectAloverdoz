#  • Сеть: адрес общего списка комнат (ntfy-совместимый сервер), автосохранение комнаты.
# Вызывается из gen_core.py последним; всё правится в редакторе.


def P(shape, size, pos, color, mat="metal", rot=(0, 0, 0), **kw):
    d = {"shape": shape, "size": list(size), "pos": list(pos), "rot": list(rot), "color": color, "mat": mat}
    d.update(kw)
    return d


