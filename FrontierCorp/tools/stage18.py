def _coop(settings):
    c = settings.setdefault("coop", {})
    c.setdefault("lobby", True)
    c.setdefault("lobby_url", "https://ntfy.sh")
    c.setdefault("lobby_topic", "frontiercorp_rooms_v2")
    c.setdefault("lobby_every", 240)
    c.setdefault("lobby_window", 300)
    c.setdefault("ip_url", "https://api.ipify.org")
    c.setdefault("autosave_min", 2.0)
    settings.setdefault("builders", {"ruin_keep_min": 40.0, "rebuild_bot_s": 45.0, "rebuild_cost": {"iron_plate": 5, "circuit": 2},
                                     "threat_r": 4.0, "show_ruins": True})


