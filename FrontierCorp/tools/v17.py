# Версия 1.7 (28.10): что попросили после игры на выделенном сервере.
#  • Кустов с волокном вдвое больше (и пара у места высадки).
#  • Обучение: шаг «Провод» заменён на «Станция энергии» и «Энергия» (по умолчанию энергия идёт через станции, а не провода),
#    после конвейера — шаг «Снос».
#  • Топор: режим «оставлять пни / корчевать» (клавиша поворота с топором в руках).
# Вызывается из gen_core.py последним; всё правится в редакторе.


def apply(settings, world, items, quests):
    n = 0
    # ---------------------------------------------------------------- волокно ×2
    for f in world.get("flora", []):
        if f.get("resource") == "bush_fiber":
            f["density"] = round(float(f.get("density", 0.03)) * 2, 4)
            n += 1
    sg = world.setdefault("start_gatherables", {})
    sg["bush_fiber"] = max(int(sg.get("bush_fiber", 0)), 4)
    # ---------------------------------------------------------------- топор
    for k in ("stone_axe", "iron_axe"):
        if k in items:
            d = items[k].get("desc", "")
            if "пни" not in d:
                items[k]["desc"] = d + " {key:rotate} с топором в руках — режим: оставлять пни (из них снова вырастут деревья) или корчевать."
            n += 1
    # ---------------------------------------------------------------- обучение
    steps = settings["tutorial"]["steps"]
    out = []
    for st in steps:
        t = st.get("title", "")
        if t == "Брёвна":
            st = dict(st, hint="Брёвна нужны для верстака и досок. Пни топор не трогает — из них снова вырастут деревья "
                               "({key:rotate} с топором в руках — корчевать пни).")
        if t == "Провод":
            out.append({"title": "Станция энергии",
                        "text": "Генератор даёт энергию, а до зданий её доносят [b]станции энергии[/b]. Поставьте станцию ({key:build_menu}, раздел «Энергетика») "
                                "рядом с буром: всё, что в её круге, получает энергию. Станции связываются с генератором и друг с другом "
                                "на расстоянии до 8 клеток. Станция: 2 доски и 2 провода.",
                        "goal": "build", "building": "pole", "n": 1, "can_skip": True, "highlight": "",
                        "hint": "Провода делаются в мастерской из медных слитков: медную руду плавьте в печи, как железо."})
            out.append({"title": "Энергия",
                        "text": "Нажмите {key:wire} — откроется [b]карта энергии[/b]: круги станций и линии связи. Бур должен стоять внутри круга, "
                                "а станция — рядом с генератором. Положите в генератор топливо, и бур заработает. "
                                "Счёт за электричество корпорация великодушно берёт на себя.",
                        "goal": "powered", "n": 1, "can_skip": True, "highlight": "",
                        "hint": "Не хватает мощности? Ещё один генератор рядом или станция выше уровнем. Снова {key:wire} — закрыть карту."})
            n += 1
            continue
        out.append(st)
        if t == "Конвейер":
            out.append({"title": "Снос",
                        "text": "Поставили не туда? Нажмите {key:demolish} — включится [b]снос[/b]. Кликните по лишнему зданию или куску ленты: "
                                "всё потраченное вернётся в рюкзак. Зажмите кнопку и ведите мышью — снесёте целую линию.",
                        "goal": "demolish", "n": 1, "can_skip": True, "highlight": "",
                        "hint": "ПКМ или Esc — выйти из сноса. Штаб снести нельзя: он слишком важен для отчётности."})
            n += 1
    settings["tutorial"]["steps"] = out
    # ---------------------------------------------------------------- задания
    if "q_miner" in quests:
        quests["q_miner"]["text"] = "Поставьте бур на залежь руды и станцию энергии рядом с ним и генератором (V — карта энергии)"
    return n
