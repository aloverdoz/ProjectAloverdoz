def apply(settings, menu, texts, options=None):
    n = 0
    for sec in (options or {}).get("sections", []):
        if sec.get("id") == "game" and not any(it.get("key") == "quips_on" for it in sec["items"]):
            sec["items"].append({"key": "quips_on", "name": "Шутки «Радио Aloverdoz» в сообщениях", "type": "check", "default": True})
    tut = settings.get("tutorial", {})
    for st in tut.get("steps", []):
        new = TUTOR.get(st.get("title", ""))
        if not new:
            continue
        st["title"], st["text"] = new[0], new[1]
        if new[2] is not None and new[2] != "":
            st["hint"] = new[2]
        n += 1
    settings["quips"] = QUIPS
    settings.setdefault("quip_cooldown", 45.0)
    settings.setdefault("quip_chance", 0.7)
    settings.setdefault("quip_name", "Радио " + CORP)
    have = {t.get("text") for t in menu.get("tips", [])}
    for t in TIPS:
        if t not in have:
            menu.setdefault("tips", []).append({"text": t})
    for k, v in TEXTS.items():
        texts[k] = v
    return n
