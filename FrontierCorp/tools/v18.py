def _bm_model():
    P = []
    def box(size, pos, color, mat="paint", rot=(0, 0, 0), **kw):
        d = {"shape": "box", "size": list(size), "pos": list(pos), "rot": list(rot), "color": color, "mat": mat}
        d.update(kw)
        P.append(d)
    box((1.9, 0.14, 1.9), (0, 0.07, 0), "#3a3d44", "dark", bevel=0.02)
    box((1.5, 1.35, 1.3), (0, 0.82, 0), "#2b2432", bevel=0.04)
    box((1.7, 0.1, 1.55), (0, 1.55, 0), "#1c1a22", "dark", rot=(8, 0, 0))
    box((1.2, 0.5, 0.06), (0, 1.1, 0.66), "#120f16", "dark")
    box((1.0, 0.16, 0.05), (0, 1.75, 0.55), "#ff2f5a", "glow", emission=2.5)
    box((0.5, 0.12, 0.5), (0, 0.55, -0.72), "#55505e", "metal")
    box((0.6, 0.08, 0.6), (0, 0.62, -0.72), "#ff2f5a", "glow", emission=1.2)
    P.append({"shape": "cylinder", "size": [0.34, 0.06, 0.34], "pos": [0.45, 1.25, 0.69], "rot": [90, 0, 0], "color": "#ffd36b", "mat": "metal"})
    P.append({"shape": "cylinder", "size": [0.22, 0.07, 0.22], "pos": [-0.42, 1.0, 0.69], "rot": [90, 0, 0], "color": "#ffd36b", "mat": "metal"})
    for x in (-0.7, 0.7):
        box((0.08, 1.4, 0.08), (x, 0.84, 0.62), "#ff2f5a", "glow", emission=0.8)
    return {"name": "Чёрный рынок", "category": "Логистика", "parts": P}


def _lift_model(color):
    # вдоль X от −1 (низ, вход) до +1 (верх, выход); высота 1 — растягивается под разницу ярусов
    import math
    a = math.degrees(math.atan2(1.0, 2.0))
    P = [
        {"shape": "box", "size": [2.24, 0.16, 1.15], "pos": [0, 0.5, 0], "rot": [0, 0, a], "color": "#6b7079", "mat": "belt"},
        {"shape": "box", "size": [2.24, 0.14, 0.09], "pos": [0, 0.6, 0.62], "rot": [0, 0, a], "color": color, "mat": "paint"},
        {"shape": "box", "size": [2.24, 0.14, 0.09], "pos": [0, 0.6, -0.62], "rot": [0, 0, a], "color": color, "mat": "paint"},
    ]
    for x, h in ((0.85, 0.92), (0.0, 0.5)):
        for z in (0.55, -0.55):
            P.append({"shape": "cylinder", "size": [0.1, h, 0.1], "pos": [x, h * 0.5, z], "rot": [0, 0, 0], "color": "#2b3138", "mat": "metal"})
    P.append({"shape": "box", "size": [0.3, 0.05, 1.3], "pos": [0.85, 0.02, 0], "rot": [0, 0, 0], "color": "#2b3138", "mat": "dark"})
    P.append({"shape": "box", "size": [0.3, 0.05, 1.3], "pos": [0.0, 0.02, 0], "rot": [0, 0, 0], "color": "#2b3138", "mat": "dark"})
    return {"name": "Лифт для предметов", "category": "Логистика", "parts": P}


