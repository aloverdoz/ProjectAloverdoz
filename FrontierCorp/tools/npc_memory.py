def apply(enemies, settings):
    settings["npc_characters"] = CHARACTERS
    settings["npc_names"] = "\n".join(NAMES)
    settings["npc_return_chance"] = 0.6
    settings["npc_rel_hurt"] = 12
    settings["npc_bandit_revenge_from"] = 3
    for k, v in enemies.items():
        b = v.get("behavior", "")
        if b in ("trader", "traveler", "infiltrator"):
            v.setdefault("characters", ["kind", "greedy", "grumpy", "coward", "proud"])
        elif b == "bandit":
            v.setdefault("characters", ["cruel", "cunning"])
