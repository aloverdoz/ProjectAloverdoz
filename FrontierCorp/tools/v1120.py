# Версия 1.1.20: тексты обучения про ручные станции (верстак, мастерская) и кирку.
# Вызывается из gen_core.py последним.


def apply(settings):
    n = 0
    tut = settings.get("tutorial", {})
    for s in tut.get("steps", []) if isinstance(tut, dict) else []:
        t = s.get("text", "")
        if s.get("item") == "plank" and "положите брёвна" in t:
            s["text"] = ("Подойдите к верстаку и откройте окно крафта ({key:craft}) — рядом с верстаком появится вкладка "
                         "[b]«Верстак»[/b] (или {key:interact} по верстаку → «Открыть крафт»). Сделайте [b]«Доски»[/b]: брёвна берутся "
                         "прямо из рюкзака, из одного бревна выходит 3 доски. Наберите 25 досок: 15 уйдут на открытие, 10 — на мастерскую.")
            s["n"] = 25
            s["hint"] = "Верстак работает, пока вы стоите рядом. Нажмите на рецепт несколько раз — изделия встанут в очередь."
            n += 1
        if s.get("item") == "gear" and "положите слитки" in t:
            s["text"] = ("Подойдите к мастерской и откройте окно крафта ({key:craft}), вкладка [b]«Мастерская»[/b]. "
                         "Сделайте [b]«Шестерню»[/b] (2 слитка из рюкзака) — нужно 6 шестерней для генератора и бура.")
            n += 1
        if s.get("item") == "stone_pickaxe" and "не добыть совсем" in t:
            s["text"] = t.replace("а руду без неё не добыть совсем", "а руду голыми руками добывать очень долго")
            n += 1
        if s.get("tech") == "t_workshop" and "Стартовых кредитов хватит на первые открытия." in t:
            s["text"] = t.replace("Стартовых кредитов хватит на первые открытия.", "Стартовых кредитов хватит на первые открытия (в «Хардкоре» и «Безумии» их нет — кредиты дают продажа и задания).")
            n += 1
    return n
